// Static build for the "Automations in T3 Code" mockup site.
//
//   node tools/build.mjs            → generates js/icons.js, js/palettes.js and styles.css
//   node tools/build.mjs --watch    → rebuilds styles.css when index.html / js/** / theme.css change
//
// Nothing is installed here: tailwindcss + lucide are borrowed from the decompiled Automations UI
// app's node_modules, and the T3 Code theme palettes are read straight out of the a3 code repo
// (Node strips the TypeScript types when importing that file).
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, watch, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, "..");
const PROJECT = resolve(ROOT, "../..");
const APP_NODE_MODULES = join(PROJECT, "Automations UI/app/node_modules");
const T3_PALETTES = join(PROJECT, "a3 code/packages/shared/src/themePalettes.ts");
const req = createRequire(join(APP_NODE_MODULES, "x.js"));
const { compile, optimize } = await import(pathToFileURL(req.resolve("@tailwindcss/node")).href);
const { Scanner } = req("@tailwindcss/oxide");

