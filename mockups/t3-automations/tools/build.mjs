async function buildIcons() {
  const out = {};
  for (const name of LUCIDE) {
    const file = join(APP_NODE_MODULES, "lucide-react/dist/esm/icons", `${name}.mjs`);
    let src;
    try { src = readFileSync(file, "utf8"); } catch { console.warn(`[icons] missing lucide icon: ${name}`); continue; }
    const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
    if (!m) { console.warn(`[icons] could not parse ${name}`); continue; }
    // The node array is plain JSON-ish JS: ["path", { d: "...", key: "..." }]
    const node = new Function(`return ${m[1]}`)();
    out[name] = node
      .map(([tag, attrs]) => {
        const a = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ");
        return `<${tag} ${a}/>`;
      })
      .join("");
  }
  const body = `// Generated by tools/build.mjs — lucide ${req("lucide-react/package.json").version} icon bodies.\n` +
    `// Usage: icon("calendar", "size-4") → <svg …>. Attributes mirror lucide's defaults (24px box, 2px round strokes).\n` +
    `window.LUCIDE = ${JSON.stringify(out, null, 0)};\n`;
  writeFileSync(join(ROOT, "js/icons.js"), body);
  console.log(`[icons] ${Object.keys(out).length} lucide icons → js/icons.js`);
}

/* --------------------------------------------------------------- palettes */
async function buildPalettes() {
  const mod = await import(pathToFileURL(T3_PALETTES).href);
  const themes = Object.values(mod).filter((v) => v && typeof v === "object" && "colors" in v && "id" in v);
  const compact = themes.map((t) => ({ id: t.id, label: t.label, appearance: t.appearance, colors: t.colors, variants: t.variants ?? {}, sidebarArtwork: t.sidebarArtwork ?? false }));
  const body = `// Generated by tools/build.mjs from a3 code/packages/shared/src/themePalettes.ts\n` +
    `window.T3_THEMES = ${JSON.stringify(compact)};\n`;
  writeFileSync(join(ROOT, "js/palettes.js"), body);
  console.log(`[palettes] ${compact.map((t) => t.id).join(", ")} → js/palettes.js`);
}

/* -------------------------------------------------------------------- css */
async function buildCss() {
  const t0 = performance.now();
  const css = readFileSync(join(ROOT, "theme.css"), "utf8");
  const compiler = await compile(css, {
    base: ROOT,
    onDependency: () => {},
    customCssResolver: async (id) => {
      if (id === "tailwindcss") return join(APP_NODE_MODULES, "tailwindcss/index.css");
      if (id.startsWith("tailwindcss/")) return join(APP_NODE_MODULES, id);
      return undefined;
    },
  });
  const scanner = new Scanner({
    sources: [
      { base: ROOT, pattern: "index.html", negated: false },
      { base: join(ROOT, "js"), pattern: "**/*.js", negated: false },
      { base: ROOT, pattern: "safelist.txt", negated: false },
    ],
  });
  const candidates = scanner.scan();
  const built = compiler.build(candidates);
  const { code } = optimize(built, { minify: false });
  writeFileSync(join(ROOT, "styles.css"), code);
  console.log(`[css] ${candidates.length} candidates → styles.css (${(code.length / 1024).toFixed(1)} KB) in ${Math.round(performance.now() - t0)}ms`);
}

await buildIcons();
await buildPalettes();
await buildCss();

if (process.argv.includes("--watch")) {
  let timer;
  const schedule = () => { clearTimeout(timer); timer = setTimeout(() => buildCss().catch((e) => console.error(e)), 80); };
  watch(join(ROOT, "js"), { recursive: true }, schedule);
  for (const f of ["index.html", "theme.css", "safelist.txt"]) { try { watch(join(ROOT, f), schedule); } catch {} }
  console.log("[build] watching…");
}
